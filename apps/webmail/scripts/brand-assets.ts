/**
 * Builds the 5050 Mail brand derivatives from the 5050 brand kit files in
 * client/public/brand/ (copied unchanged from the 5050 brand kit):
 *
 *   client/src/components/brand/paths.ts   mark plates (bare 5050 mark, no text lockup)
 *   client/public/brand/favicon-32.png     from favicon.svg (Fold, the brand's favicon)
 *   client/public/brand/og-image.png       1200x630 link-preview card
 *
 *   npm run brand
 *
 * Needs Playwright's Chromium for the PNGs.
 * Fonts: Archivo and JetBrains Mono (both OFL) from @fontsource, self-hosted.
 */
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url).pathname;
const pub = `${root}client/public/brand/`;
const font = (p: string) => readFileSync(`${root}node_modules/${p}`).toString('base64');

// ---------------------------------------------------------------- mark + wordmark
function plates(svg: string) {
  const groups = [...svg.matchAll(/<g class="pl [^"]*" fill="(#[0-9A-Fa-f]{6})">(.*?)<\/g>/g)];
  if (groups.length !== 2) throw new Error('unexpected 5050-logo.svg structure');
  return groups.map(([, fill, body]) => ({ fill: fill!, paths: [...body!.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]!) }));
}
const [lime, aqua] = plates(readFileSync(`${pub}5050-logo.svg`, 'utf8'));
const [limeDark, aquaDark] = plates(readFileSync(`${pub}5050-logo-dark.svg`, 'utf8'));

// Geometry on the brand kit's 989 x 428 artboard. The mark's glyphs sit in
// MARK_VB (bounds plus a little bleed, as in the brand kit's LogoMark).
const MARK_VB = { x: 96, y: 44, w: 844, h: 352 };

writeFileSync(
  `${root}client/src/components/brand/paths.ts`,
  `// Generated by scripts/brand-assets.ts from client/public/brand/5050-logo*.svg (5050 brand kit)
// Do not edit by hand.

/** Lime "50" plate. */
export const LIME_PLATE = ${JSON.stringify(lime!.paths)} as const;
/** Aqua "50" plate (multiplied over lime in light mode, screened in dark). */
export const AQUA_PLATE = ${JSON.stringify(aqua!.paths)} as const;
export const PLATE_INKS = {
  light: { lime: '${lime!.fill}', aqua: '${aqua!.fill}' },
  dark: { lime: '${limeDark!.fill}', aqua: '${aquaDark!.fill}' },
} as const;
/** Glyph bounds of the mark on the 989 x 428 artboard, with a little bleed. */
export const MARK_VB = ${JSON.stringify(MARK_VB)} as const;
`,
);

// ---------------------------------------------------------------- PNGs
const INK = '#1C1A24';
const INK2 = '#47424F';
const INK3 = '#6E6878';
const PAPER = '#F4EFE3';

const markSvg = (h: number) =>
  `<svg height="${h}" viewBox="${MARK_VB.x} ${MARK_VB.y} ${MARK_VB.w} ${MARK_VB.h}" style="isolation:isolate;display:block">` +
  `<g fill="${lime!.fill}">${lime!.paths.map((d) => `<path d="${d}" fill-rule="evenodd"/>`).join('')}</g>` +
  `<g fill="${aqua!.fill}" style="mix-blend-mode:multiply">${aqua!.paths.map((d) => `<path d="${d}" fill-rule="evenodd"/>`).join('')}</g></svg>`;

const og = `<!doctype html><html><head><style>
@font-face{font-family:Archivo;src:url(data:font/woff2;base64,${font('@fontsource-variable/archivo/files/archivo-latin-wdth-normal.woff2')}) format('woff2');font-weight:100 900;font-stretch:62% 125%}
@font-face{font-family:'JetBrains Mono';src:url(data:font/woff2;base64,${font('@fontsource/jetbrains-mono/files/jetbrains-mono-latin-700-normal.woff2')}) format('woff2');font-weight:700}
*{box-sizing:border-box;margin:0}
body{width:1200px;height:630px;background:${PAPER};color:${INK};font-family:Archivo,sans-serif}
.card{position:relative;width:100%;height:100%;padding:64px 72px;display:flex;flex-direction:column;justify-content:space-between}
.label{font:700 22px/1 'JetBrains Mono',monospace;letter-spacing:2px;color:${INK2};margin-bottom:22px}
h1{font-weight:900;font-stretch:112%;font-size:96px;line-height:.9;letter-spacing:-.03em;text-transform:uppercase;white-space:nowrap}
p{font-weight:500;font-size:34px;line-height:1.25;color:${INK2};margin-top:26px}
.foot{display:flex;align-items:center;gap:20px;font:700 22px/1 'JetBrains Mono',monospace;letter-spacing:2px;color:${INK3}}
.chip{background:${lime!.fill};color:${INK};border:3px solid ${INK};border-radius:999px;padding:10px 22px;transform:rotate(-4deg)}
</style></head><body><div class="card">
<div>${markSvg(96)}</div>
<div><div class="label">OPEN-SOURCE WEBMAIL</div><h1>5050 Mail</h1>
<p>Self-hosted business email on your own domains.</p></div>
<div class="foot"><span class="chip">SIGN IN</span><span>AGPL-3.0</span></div>
</div></body></html>`;

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
  await page.setContent(og);
  await page.evaluate(() => document.fonts.ready);
  const fits = await page.evaluate(() => {
    const h = document.querySelector('h1')!;
    return h.scrollWidth <= h.clientWidth;
  });
  if (!fits) throw new Error('OG headline does not fit on one line');
  await page.screenshot({ path: `${pub}og-image.png` });

  const fav = await browser.newPage({ viewport: { width: 32, height: 32 }, deviceScaleFactor: 1 });
  const favSvg = readFileSync(`${pub}favicon.svg`, 'utf8').replace(/ width="\d+" height="\d+"/, ' width="32" height="32"');
  await fav.setContent(`<!doctype html><style>*{margin:0}svg{display:block}</style>${favSvg}`);
  await fav.screenshot({ path: `${pub}favicon-32.png`, omitBackground: true });
} finally {
  await browser.close();
}
console.log('brand assets written');
