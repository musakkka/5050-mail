const dir = join(process.cwd(), 'node_modules/@material-symbols/svg-400/outlined');
const extract = (file: string) => {
  const svg = readFileSync(file, 'utf8');
  return [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
};
const out: Record<string, string> = {};
for (const n of [...new Set(NAMES)]) {
  const f = join(dir, `${n}.svg`);
  if (!existsSync(f)) {
    console.warn('missing icon', n);
    continue;
  }
  out[n] = extract(f);
  if (FILLED.includes(n) && existsSync(join(dir, `${n}-fill.svg`))) out[`${n}:fill`] = extract(join(dir, `${n}-fill.svg`));
}
const body = `// Generated by scripts/gen-icons.ts from @material-symbols/svg-400 (Apache-2.0). Do not edit.\n// viewBox "0 -960 960 960"\nexport const ICON_PATHS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')} as const;\nexport type IconName = keyof typeof ICON_PATHS;\n`;
writeFileSync(join(process.cwd(), 'client/src/components/icons/paths.ts'), body);
